"""
Tests for the NEW CatenaryCable element (6-DOF per node).

This file is meant to be run with the *new* OpenSees build (locally compiled)
which supersedes the old implementation.  It validates the element against:

1. **Analytical solution** — the known verification example from
   Salehi Ahmad Abad et al. (2013) / OpenSeesWiki (x=30 case).
   Node-2 displacements should be (8.58693, 0, 2.82578).

2. **Old implementation reference** — compares against the results previously
   saved by ``generate_catenary_reference.py`` (run with the old
   OpenSeesPy from ``~/engineering-venv``).

3. **Self-weight equilibrium** — a simple sanity check that the vertical
   reactions sum to the total self-weight.

References:
    Salehi Ahmad Abad, M., Shooshtari, A., Esmaeili, V., & Naghavi Riabi, A. (2013).
    Nonlinear analysis of cable structures under general loadings.
    Finite Elements in Analysis and Design, 73, 11–19.
    https://doi.org/10.1016/j.finel.2013.05.002

    OpenSeesWiki — CatenaryCableElement:
    https://opensees.berkeley.edu/wiki/index.php/CatenaryCableElement
"""

import json
import math
import pathlib

try:
    import opensees as ops
except ModuleNotFoundError:
    import openseespy.opensees as ops

# ---------------------------------------------------------------------------
#  Path for the reference JSON file (generated by
#  ``generate_catenary_reference.py`` on the old OpenSeesPy)
# ---------------------------------------------------------------------------
_REFERENCE_FILE = pathlib.Path(__file__).resolve().parent / "catenary_reference.json"


# ===========================================================================
#  Helpers
# ===========================================================================

def _build_verification_model(ndf=3):
    """
    Build the 3-node, 2-element catenary model from the OpenSeesWiki example
    (Salehi Ahmad Abad 2013, x=30 case).

    Parameters
    ----------
    ndf : int
        Number of DOFs per node (3 for old, 6 for new).
    """
    ops.wipe()
    ops.model("basic", "-ndm", 3, "-ndf", ndf)

    x = 30.0
    ops.node(1, 0.0, 0.0, 90.0)
    ops.node(2, x / 2, 0.0, 40.0)
    ops.node(3, x, 60.0, 30.0)

    if ndf == 3:
        ops.fix(1, 1, 1, 1)
        ops.fix(2, 0, 1, 0)
        ops.fix(3, 1, 1, 1)
    else:
        ops.fix(1, 1, 1, 1, 1, 1, 1)
        ops.fix(2, 0, 1, 0, 1, 1, 1)
        ops.fix(3, 1, 1, 1, 1, 1, 1)

    w3 = -0.00001
    E = 3.0e7
    A = 1.0
    L0_total = 100.0
    alpha = 6.5e-6
    temperature_change = 100.0
    rho = w3 / 9.81
    error_tol = 1e-6
    N_substeps = 20
    mass_type = 0

    ops.element("CatenaryCable", 1, 1, 2,
                w3, E, A, L0_total / 2, alpha, temperature_change, rho,
                error_tol, N_substeps, mass_type)
    ops.element("CatenaryCable", 2, 2, 3,
                w3, E, A, L0_total / 2, alpha, temperature_change, rho,
                error_tol, N_substeps, mass_type)

    ops.timeSeries("Linear", 1)
    ops.pattern("Plain", 2, 1)
    ops.eleLoad("-ele", 1, 2, "-type", "-beamUniform", 0.0, 0.0, -1.0)

    ops.system("Diagonal")  # Avoid MKL sparse solver
    ops.constraints("Plain")
    ops.numberer("Plain")
    ops.test("NormDispIncr", 1.0e-5, 100, 1)
    ops.integrator("LoadControl", 1.0 / 10)
    ops.algorithm("Newton")
    ops.analysis("Static")
    ops.analyze(10)


def _get_element_forces(ele_tags):
    """Return {tag: [forces]} for each element tag."""
    return {str(tag): [float(v) for v in ops.eleForce(tag)] for tag in ele_tags}


def _get_node_displacements(node_tags, ndof=3):
    """Return {tag: [disp]} for each node tag."""
    return {str(tag): [ops.nodeDisp(tag, i + 1) for i in range(ndof)]
            for tag in node_tags}


